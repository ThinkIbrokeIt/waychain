#!/usr/bin/env bash
# Wrapper for version-drift-check.sh with fingerprint-based duplicate avoidance
# Replaces the current pre-run script logic

set -euo pipefail

REPO="ThinkIbrokeIt/waychain"
DRIFT_CHECK_SCRIPT="/home/wink/projects/waychain/scripts/version-drift-check.sh"

# Run the drift check, capture output and exit code
# Using || to capture exit code without triggering set -e
DRIFT_OUTPUT=$("$DRIFT_CHECK_SCRIPT" 2>&1) || DRIFT_EXIT=$?

# If the command succeeded, exit code is 0
if [[ ! -v DRIFT_EXIT ]]; then
    DRIFT_EXIT=0
fi

if [[ $DRIFT_EXIT -eq 0 ]]; then
    echo "��������������✅ No drift detected"
    exit 0
fi

echo "$DRIFT_OUTPUT"

# Handle SSH timeout/failure as infrastructure issue (not drift)
if echo "$DRIFT_OUTPUT" | grep -q "Connection timed out\|Failed to get live binary hash via SSH"; then
    echo "��������������⚠��������������️  SSH connection failure - infrastructure issue, not drift"
    exit 0
fi

# Handle RPC down (Cloudflare error 1033 / origin unreachable) as infrastructure issue
if echo "$DRIFT_OUTPUT" | grep -q "jq: parse error: Invalid numeric literal\|Failed to get chain ID from live node\|Cloudflare error 1033\|error code: 1033"; then
    echo "��������������⚠��������������️  RPC down (Cloudflare error 1033) - infrastructure issue, not drift"
    # Extract error code for fingerprint
    RPC_ERROR=$(echo "$DRIFT_OUTPUT" | grep -oE "error code: [0-9]+" | awk '{print $3}' || echo "1033")
    DRIFT_FINGERPRINT="rpc-down:${RPC_ERROR}"
    DRIFT_TYPE="rpc-down"
    
    # Check for existing issue with matching fingerprint
    EXISTING_ISSUE=$(gh issue list --repo "$REPO" --search "[DRIFT]" --state open --json number,body -q ".[] | select(.body | contains(\"${DRIFT_FINGERPRINT}\")) | .number" 2>/dev/null | head -1 || true)
    
    if [[ -n "$EXISTING_ISSUE" ]]; then
        echo "Issue #$EXISTING_ISSUE already open for this drift (fingerprint: $DRIFT_FINGERPRINT). Updating with latest output."
        gh issue comment "$EXISTING_ISSUE" --repo "$REPO" --body "**Latest drift check update ($(date -u +%Y-%m-%dT%H:%M:%SZ)):**

\`\`\`
$DRIFT_OUTPUT
\`\`\`" 2>/dev/null || true
    else
        echo "No existing issue for RPC down - creating new one (unexpected, should have been caught by cron)"
        TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
        ISSUE_TITLE="[DRIFT] ${DRIFT_TYPE}: rpc-down:${RPC_ERROR}"
        ISSUE_BODY="## Drift Detection Report

**Timestamp:** $TIMESTAMP
**Drift type:** $DRIFT_TYPE
**Fingerprint:** \`$DRIFT_FINGERPRINT\`

### Findings

\`\`\`
$DRIFT_OUTPUT
\`\`\`

### Action Required
The public RPC endpoint at \`api.waychain.org\` is returning **Cloudflare error 1033** (\"Origin Unreachable\"), meaning the Cloudflare tunnel cannot reach the origin server (the WayChain node on AWS at 3.89.116.45:9545).

This is a **critical infrastructure outage** - the public RPC is completely down. All external clients (explorer, wallet, faucet, third-party integrations) cannot query the chain.

### Root Cause Analysis
Two known infrastructure issues compounding:
1. **SSH to AWS timed out** - since August 2026 (blocks binary verification & redeploy)
2. **Cloudflare tunnel origin unreachable** - the node on AWS port 9545 is not responding to the tunnel

The node may be:
- Crashed/stopped (systemd service down)
- Running but not listening on port 9545
- Network/firewall blocking the Cloudflare tunnel connection
- AWS instance unreachable (security group, instance state)

### Action Required
1. **Verify AWS instance state** - check if EC2 instance 3.89.116.45 is running
2. **Check node service** - \`systemctl status waychain.service\` on the AWS host
3. **Check port 9545** - \`ss -tlnp | grep 9545\` on the AWS host
4. **Check Cloudflare tunnel** - \`cloudflared tunnel status\` or check Cloudflare dashboard
5. **If node is down** - rebuild consensus with \`go build -a\` and redeploy binary
6. **If tunnel is down** - restart cloudflared service

### Related Issues
- #194: Binary hash drift (live binary hash unknown due to SSH timeout since Aug 2026)
- #202: Version-number drift (monorepo 4.1.39 vs site 4.1.35)
- #190: Cross-repo version sync (monorepo vs site version.json)

